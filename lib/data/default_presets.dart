DrugPreset buildDrugPreset({
  required String name,
  required String doseUnit,
  required double drugAmount,
  required String drugUnit,
  required double volumeMl,
  required String timeUnit,
  required bool useWeight,
  required String note,
  double? minDose,
  double? maxDose,
}) {
  return DrugPreset(
    id: uniqueId(),
    name: name,
    doseUnit: doseUnit,
    minDose: minDose,
    maxDose: maxDose,
    drugAmount: drugAmount,
    drugUnit: drugUnit,
    volumeMl: volumeMl,
    timeUnit: timeUnit,
    useWeight: useWeight,
    note: note,
  );
}

String buildPresetNote({
  required String mix,
  String? initial,
  String? max,
  String? extra,
}) {
  return [
    mix,
    if (initial != null && initial.trim().isNotEmpty) 'Initial $initial',
    if (max != null && max.trim().isNotEmpty) 'Max $max',
    if (extra != null && extra.trim().isNotEmpty) extra.trim(),
  ].join('\n');
}

bool _isLegacyNcuMgso4Name(String name) {
  final normalized = name.trim().toLowerCase();
  return normalized == 'mgso4 (sah)' || normalized == 'mgso4 (ttm)';
}

